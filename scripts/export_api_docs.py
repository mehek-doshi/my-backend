"""Regenerates docs/api.md from the running application's OpenAPI schema, so the documentation cannot drift from the code.

    python scripts/export_api_docs.py            (run from the backend folder)
"""
import os
import sys
from pathlib import Path

os.environ.setdefault("ENVIRONMENT", "development")
os.environ.setdefault("AUTH_MODE", "dev")
os.environ.setdefault("ALLOW_DEV_AUTH", "true")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.api.v1 import admin, artifacts, categories, discovery, me, sources, system, topics, volunteering  # noqa: E402
import inspect  # noqa: E402

MODULES = (system, categories, sources, topics, discovery, volunteering, artifacts, me, admin)


def _roles(call):
    return inspect.getclosurevars(call).nonlocals.get("allowed")


def access_for(route) -> str:
    """Read the access rule from the endpoint's dependencies (the same objects FastAPI enforces)."""
    def walk(dep):
        for d in dep.dependencies:
            if "require_roles" in str(d.call):
                return " or ".join(sorted(r.value for r in _roles(d.call)))
            if getattr(d.call, "__name__", "") == "current_user":
                return "Any signed-in user"
            found = walk(d)
            if found:
                return found
        return None
    return walk(route.dependant) or "Public"


def main() -> None:
    rows: dict[str, list[tuple[str, str]]] = {}
    for module in MODULES:
        for route in module.router.routes:
            tag = (route.tags or ["other"])[0]
            doc = (route.endpoint.__doc__ or "").strip().splitlines()
            for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
                path = "/api/v1" + route.path
                rows.setdefault(tag, []).append((path, f"| `{method}` | `{path}` | {access_for(route)} | {doc[0] if doc else ''} |"))
    out = ["# API reference", "",
           "Generated by `scripts/export_api_docs.py` from the application's routes. Interactive docs (`/docs`) are available "
           "when `ENVIRONMENT` is not `production`.", "",
           "All paths are under `/api/v1`. Errors always look like "
           '`{"error": {"code", "message", "details", "request_id"}}`. List endpoints return '
           '`{"items", "total", "limit", "offset"}` (`limit` 1-100, default 25).', ""]
    for tag in sorted(rows):
        out += [f"## {tag}", "", "| Method | Path | Who | Notes |", "|---|---|---|---|", *[r for _, r in sorted(rows[tag])], ""]
    Path(__file__).resolve().parents[2].joinpath("docs/api.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/api.md")


if __name__ == "__main__":
    main()
